import 'package:firebase_core/firebase_core.dart';
import 'package:flutter/material.dart' hide Text;

import 'firebase_options.dart'; // generated by `flutterfire configure`
import 'l10n.dart';
import 'models.dart';
import 'screens/create_join_room_screen.dart';
import 'screens/home_shell.dart';
import 'screens/login_screen.dart';
import 'screens/pending_approval_screen.dart';
import 'services/app_lock.dart';
import 'services/auth_service.dart';
import 'theme.dart';
import 'widgets.dart';

Future<void> main() async {
  WidgetsFlutterBinding.ensureInitialized();
  await Firebase.initializeApp(options: DefaultFirebaseOptions.currentPlatform);
  await themeController.load();
  await language.load();
  await appLock.load();

  // Firebase Auth tells AppState who is signed in; AppState then loads their data.
  authService.authChanges.listen((user) {
    if (user == null) {
      appState.onSignedOut();
    } else if (!authService.registering) {
      appState.onSignedIn(user);
    }
  });

  runApp(const RoomMateApp());
}

class RoomMateApp extends StatelessWidget {
  const RoomMateApp({super.key});

  @override
  Widget build(BuildContext context) {
    return ListenableBuilder(
      listenable: themeController,
      builder: (context, _) => MaterialApp(
        title: 'RoomMate',
        debugShowCheckedModeBanner: false,
        scaffoldMessengerKey: messengerKey,
        theme: buildTheme(),
        darkTheme: buildTheme(dark: true),
        themeMode: themeController.mode,
        builder: (context, child) => LockGate(child: child ?? const SizedBox.shrink()),
        home: const AuthGate(),
      ),
    );
  }
}

/// Chooses the screen from the session status.
class AuthGate extends StatelessWidget {
  const AuthGate({super.key});

  @override
  Widget build(BuildContext context) {
    return ListenableBuilder(
      listenable: appState,
      builder: (context, _) {
        switch (appState.status) {
          case SessionStatus.loading:
            return const Scaffold(body: Center(child: CircularProgressIndicator()));
          case SessionStatus.signedOut:
            return const LoginScreen();
          case SessionStatus.noRoom:
            return const CreateJoinRoomScreen();
          case SessionStatus.pending:
            return const PendingApprovalScreen();
          case SessionStatus.ready:
            return const HomeShell();
          case SessionStatus.error:
            return _ErrorScreen(message: appState.errorMessage ?? 'Something went wrong.');
        }
      },
    );
  }
}

class _ErrorScreen extends StatelessWidget {
  final String message;
  const _ErrorScreen({required this.message});

  @override
  Widget build(BuildContext context) {
    return Scaffold(
      body: Center(
        child: Padding(
          padding: const EdgeInsets.all(28),
          child: Column(
            mainAxisSize: MainAxisSize.min,
            children: [
              const Icon(Icons.cloud_off_rounded, size: 56, color: AppColors.muted),
              const SizedBox(height: 14),
              Text(message, textAlign: TextAlign.center),
              const SizedBox(height: 20),
              ElevatedButton(onPressed: appState.retry, child: const Text('Try again')),
              TextButton(onPressed: authService.logout, child: const Text('Log out')),
            ],
          ),
        ),
      ),
    );
  }
}
